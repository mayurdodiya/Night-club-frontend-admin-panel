export function delay(data, ms = 400) {
  return new Promise((resolve) => setTimeout(() => resolve(data), ms))
}

function paginate(items, page, limit) {
  const start = (page - 1) * limit
  return {
    data: items.slice(start, start + limit),
    total: items.length,
    page,
    limit,
  }
}

